function readBet(input) {
  var v = clampBet(input.value, 100000);
  input.value = v;
  if (v > bal) {
    setMsgNearby(
      input,
      "Bet is higher than your balance. Lower it" +
        (bal < 100 ? " or use the Refill button at the top." : "."),
    );
    return null;
  }
  return v;
}
